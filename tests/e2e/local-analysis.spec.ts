import { readFile } from "node:fs/promises";
import { test, expect } from "./fixture";

test("reviews actual local engine output without manufacturing events", async ({ page, request }, testInfo) => {
  test.skip(!process.env.HBI_VISUAL_MATCH || !process.env.HBI_ANALYSIS_REPORT,
    "Requires the user's local original video and bound engine report; no media is downloaded");
  test.setTimeout(360000);
  const report = JSON.parse(await readFile(process.env.HBI_ANALYSIS_REPORT!, "utf8"));
  expect(report.candidates.length).toBeGreaterThan(0);
  const first = report.candidates[0];
  const api = `http://127.0.0.1:${process.env.HBI_MOCK_PORT || 54329}/rest/v1`;
  const beforeEvents = await (await request.get(`${api}/events`)).json();
  const beforeShots = await (await request.get(`${api}/shot_attempts`)).json();
  await page.setViewportSize({ width: 1672, height: 941 });
  await page.goto("/login");
  await page.getByLabel("Email").fill("coach@example.test");
  await page.getByLabel("Password").fill("test-password");
  await page.getByRole("button", { name: "Enter SESEN" }).click();
  await expect(page.getByText("HBI Test Club").first()).toBeAttached({ timeout: 90000 });
  await page.getByRole("button", { name: "English", exact: true }).click();
  await page.getByRole("link", { name: "Video Lab", exact: true }).click();
  await page.getByLabel("Match", { exact: true }).selectOption("50000000-0000-4000-8000-000000000001");
  await page.getByLabel("Select local video", { exact: false }).setInputFiles(process.env.HBI_VISUAL_MATCH!);
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.readyState)).toBeGreaterThanOrEqual(2);
  await page.getByRole("tab", { name: "Automatic analysis", exact: true }).click();
  const panel = page.locator('[data-slot="local-analysis-review"]');
  await panel.getByLabel("Import analysis or review backup").setInputFiles(process.env.HBI_ANALYSIS_REPORT!);
  await expect(panel.locator("article")).toHaveCount(report.candidates.length);
  const candidate = panel.locator(`[data-candidate-id="${first.id}"]`);
  await candidate.getByRole("button", { name: "Open evidence", exact: true }).click();
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.currentTime * 1000)).toBeCloseTo(first.video_start_ms, -2);
  await candidate.getByRole("button", { name: "Create review clip", exact: true }).click();
  await expect.poll(async () => (await (await request.get(`${api}/clips`)).json()).length).toBe(1);
  await candidate.getByRole("button", { name: "Create review clip", exact: true }).click();
  expect((await (await request.get(`${api}/clips`)).json()).length).toBe(1);
  expect(await (await request.get(`${api}/events`)).json()).toEqual(beforeEvents);
  expect(await (await request.get(`${api}/shot_attempts`)).json()).toEqual(beforeShots);
  await candidate.getByLabel("Coach notes").fill("Reviewed against original video; timing still provisional");
  await candidate.getByLabel("Coach notes").press("Tab");
  await candidate.getByRole("button", { name: "Mark reviewed", exact: true }).click();
  await panel.getByLabel("Review status").selectOption("reviewed");
  await expect(panel.locator("article")).toHaveCount(1);
  await page.screenshot({ path: testInfo.outputPath("engine-review-en-1672.png"), fullPage: true });
  await page.reload();
  await page.getByLabel("Match", { exact: true }).selectOption("50000000-0000-4000-8000-000000000001");
  await page.getByRole("tab", { name: "Automatic analysis", exact: true }).click();
  await panel.getByLabel("Review status").selectOption("reviewed");
  await expect(candidate.getByLabel("Coach notes")).toHaveValue("Reviewed against original video; timing still provisional");
  await page.setViewportSize({ width: 375, height: 844 });
  await page.getByRole("button", { name: "العربية", exact: true }).click();
  await expect(panel).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("engine-review-ar-375.png"), fullPage: true });
});
